local ok, ls = pcall(require, "luasnip")

if not ok then
	return {}
end

local s = ls.snippet
local t = ls.text_node
local i = ls.insert_node
local c = ls.choice_node

local icon = "🚀"
local tag = "[Neovim AutoGR Log]"

return {
	------------------------------------------------------------------
	-- 基础：console.log
	------------------------------------------------------------------
	s("lg", {
		t('console.log("' .. icon .. tag .. " "),
		i(1),
		t('");'),
		i(0),
	}),

	------------------------------------------------------------------
	-- choice node（if / switch）
	------------------------------------------------------------------
	s("if", {
		c(1, {
			t("if"),
			t("switch"),
		}),
		t(" ("),
		i(2),
		t({ ") {", "  " }),
		i(3),
		t({ "", "}" }),
		i(0),
	}),

	------------------------------------------------------------------
	-- Comment
	------------------------------------------------------------------
	s("cm", {
		t({
			"/*",
			" * ",
		}),
		i(1),
		t({
			"",
			" */",
		}),
		i(0),
	}),

	------------------------------------------------------------------
	-- TODO comment
	------------------------------------------------------------------
	s("cmt", {
		t({
			"/*",
			" * TODO: ",
		}),
		i(1),
		t({
			"",
			" */",
		}),
		i(0),
	}),
}
